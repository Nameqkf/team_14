# 200자 초과 시 말줄임표(...) 처리 함수
def truncate_text(text: str, max_len: int = 200) -> str:
    cleaned = " ".join(text.split())
    if len(cleaned) > max_len:
        return cleaned[:max_len] + "..."
    return cleaned


